/* Textos da V5 (JS/textos.js): entram por cima dos de cima quando a chave se repete */
if (window.TEXTOS_V5) {
  Object.keys(window.TEXTOS_V5).forEach(function (l) { Object.assign(TEXTOS[l], window.TEXTOS_V5[l]); });
}

(function () {
  var IDIOMAS = ["pt", "en"];
  var atual = "pt";

  function t(chave) {
    var d = TEXTOS[atual];
    return d && d[chave] !== undefined ? d[chave] : "";
  }

  function aplicar(idioma) {
    if (IDIOMAS.indexOf(idioma) < 0) idioma = "pt";
    atual = idioma;
    var d = TEXTOS[idioma];

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var v = d[el.dataset.i18n]; if (v !== undefined) el.textContent = v;
    });
    document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
      var v = d[el.dataset.i18nHtml]; if (v !== undefined) el.innerHTML = v;
    });
    [["i18nAlt", "alt"], ["i18nAria", "aria-label"], ["i18nHint", "data-hint"], ["i18nContent", "content"], ["i18nPlaceholder", "placeholder"], ["i18nTitle", "title"]].forEach(function (par) {
      document.querySelectorAll("[data-" + par[0].replace(/[A-Z]/g, function (m) { return "-" + m.toLowerCase(); }) + "]").forEach(function (el) {
        var v = d[el.dataset[par[0]]]; if (v !== undefined) el.setAttribute(par[1], v);
      });
    });

    document.documentElement.lang = idioma === "pt" ? "pt-br" : "en";
    document.querySelectorAll(".lang button").forEach(function (b) {
      b.setAttribute("aria-pressed", String(b.dataset.lang === idioma));
    });
    try { localStorage.setItem("idioma", idioma); } catch (e) { /* tudo bem */ }
    document.dispatchEvent(new CustomEvent("langchange", { detail: idioma }));
  }

  window.BH = { t: t, setLang: aplicar, get lang() { return atual; } };

  document.querySelectorAll(".lang button").forEach(function (b) {
    b.addEventListener("click", function () { aplicar(b.dataset.lang); });
  });

  var inicial = "pt";
  try { inicial = localStorage.getItem("idioma") || "pt"; } catch (e) { /* tudo bem */ }
  aplicar(inicial);
})();
